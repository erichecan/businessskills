# ---------- 去重后写入记忆库 ----------
p=BASE+'职场面试_记忆库.csv'
exist=set()
for r in csv.DictReader(io.open(p,encoding='utf-8-sig')):
    u=(r.get('URL') or '').strip()
    if u: exist.add(u)
    m=re.search(r'[0-9a-f]{24}',u)
    if m: exist.add(m.group(0))
added=[]
for n in NEW:
    key=n['URL']; m=re.search(r'[0-9a-f]{24}',key)
    if key in exist or (m and m.group(0) in exist): continue
    exist.add(key)
    if m: exist.add(m.group(0))
    added.append(n)
with io.open(p,'a',encoding='utf-8',newline='') as f:
    w=csv.DictWriter(f,fieldnames=['标题','URL','来源','关键词','首次收录日期','热度'])
    for n in added: w.writerow(n)
total=sum(1 for _ in io.open(p,encoding='utf-8-sig'))-1
