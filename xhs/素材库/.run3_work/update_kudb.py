    if kw in updates:
        u = updates[kw]
        row["状态"] = u["状态"]
        if "意图强度" in u:
            row["意图强度"] = u["意图强度"]
        if "竞争密度" in u:
            row["竞争密度"] = u["竞争密度"]
        old_note = row.get("备注","")
        row["备注"] = (old_note + " | " if old_note else "") + u["备注_add"]
