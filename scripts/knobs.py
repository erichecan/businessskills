#!/usr/bin/env python3
"""旋钮 —— 全仓库可调参数的单一真相源。

## 为什么要这个模块（不只是为了配个页面）

改之前这些数散在 6 个文件里，靠注释提醒人手动同步。最典型的是 `PASS_SCORE`：
`refine_loop.py` 和 `independent_audit.py` 各定义了一次，而后者的注释白纸黑字写着
「必须与 refine_loop.PASS_SCORE 保持同一个数，两处不同步会重演 2026-08-05 那个 bug」。
同一个病这个仓库已经犯过四次（评分卡权重 vs 写稿 prompt、审核输出模板、CTA、PASS_SCORE），
每次都是「改了一处漏了另一处」，最长漏了一个月。
集中成一份之后，这类 bug 在结构上不可能再发生。

## 三层结构

    SCHEMA（本文件）  默认值 + 范围 + 说明 + **依据** —— 跟代码一起走 git
    config/knobs.json 只存被改过的值（overrides）—— 删掉它就回到全默认
    K("NAME")         读取 + 范围校验，越界拒绝并回退默认

⛔ knobs.json 和 knobs-changelog.csv **都进版本库，不要 gitignore**。
它们是机器本地配置没错，但这个仓库的规矩是改动必须留痕：不进 git 的话，
「某个阈值什么时候被谁改成这样的」在历史里就查不到 —— 而 VIEWS_BASE 拖了一个月
没人调、评分卡权重改了三次没人对得上，全是这一类账没记住的后果。

## ⛔ `依据` 字段是硬要求，不是文档

这个仓库的规矩是「样本不够不动权重」。旋钮页上如果不写清楚某个数
**是实测标定的还是拍板选的**，调的人会以为它们一样可靠 ——
而实际上 MIN_SLOT_STRENGTH 有 693 条样本撑着，MATERIAL_PER_DRAFT 一条样本都没有。
所以每个旋钮必须声明 evidence 等级：
    measured  实测标定，动它之前先看那批数据
    decided   拍板选的，没有样本支撑，随时可调
    contract  不是旋钮是契约（列下标、退出码），**不进页面**

用法：
    from knobs import K
    if score >= K("PASS_SCORE"): ...
"""
