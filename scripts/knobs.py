SCHEMA = {
    k: {"group": g, "key": k, "default": d, "type": t.__name__, "min": lo, "max": hi,
        "step": st, "unit": u, "label": lb, "desc": ds, "evidence": ev, "basis": bs}
    for (g, k, d, t, lo, hi, st, u, lb, ds, ev, bs) in _S
}
_TYPES = {"int": int, "float": float}


def _overrides() -> dict:
    if not CONFIG.exists():
        return {}
    try:
        d = json.loads(CONFIG.read_text(encoding="utf-8"))
        return d if isinstance(d, dict) else {}
    except (json.JSONDecodeError, OSError):
        # ⛔ 配置文件坏了不能让整条流水线停 —— 回到全默认并说出来。
        print(f"⚠️ {CONFIG} 解析失败，本次全部回退默认值", flush=True)
        return {}


def K(name: str):
    """取一个旋钮的当前值。越界或类型不对 → 回退默认并告警，不抛异常。

    ⛔ 不抛异常是刻意的：这些脚本跑在 launchd 里，一个手滑的配置值不该让
    整晚的采集/写稿全部停摆。但也**不能静默** —— 静默降级正是这个仓库
    栽过好几次的病（采集报错误原因报了 5 天）。所以回退 + 打印。
    """
    s = SCHEMA.get(name)
    if s is None:
        raise KeyError(f"未定义的旋钮：{name}（SCHEMA 里没有，别在调用处凭空造）")
    raw = _overrides().get(name, s["default"])
    caster = _TYPES[s["type"]]
    try:
        v = caster(raw)
    except (TypeError, ValueError):
        print(f"⚠️ 旋钮 {name}={raw!r} 类型不对，回退默认 {s['default']}", flush=True)
        return s["default"]
    if not (s["min"] <= v <= s["max"]):
        print(f"⚠️ 旋钮 {name}={v} 超出范围 [{s['min']}, {s['max']}]，"
              f"回退默认 {s['default']}", flush=True)
        return s["default"]
    return v


def all_values() -> dict:
    return {k: K(k) for k in SCHEMA}


def changed() -> dict:
    """被改过的旋钮：{name: (当前值, 默认值)}。"""
    return {k: (K(k), SCHEMA[k]["default"]) for k in SCHEMA
            if K(k) != SCHEMA[k]["default"]}


if __name__ == "__main__":
    ch = changed()
    print(f"旋钮 {len(SCHEMA)} 个 · 改过 {len(ch)} 个 · 配置 {CONFIG}")
    for g in dict.fromkeys(s["group"] for s in SCHEMA.values()):
        print(f"\n【{g}】")
        for k, s in SCHEMA.items():
            if s["group"] != g:
                continue
            v = K(k)
            mark = f"  ← 默认 {s['default']}" if k in ch else ""
            ev = {"measured": "实测", "decided": "拍板"}[s["evidence"]]
            print(f"  {k:24s} {v!s:>6s} {s['unit']:<6s} [{ev}] {s['label']}{mark}")
